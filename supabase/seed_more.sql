-- ============================================================
-- 평점·리뷰수 재계산 (기존 3건 포함 전체)
-- ============================================================
update jobs
set review_count = coalesce(sub.cnt, 0),
    rating       = coalesce(sub.avg_rating, 0)
from (
  select job_id, count(*) as cnt, round(avg(rating)::numeric, 1) as avg_rating
  from job_reviews
  group by job_id
) as sub
where jobs.id = sub.job_id;

