-- 리뷰 개수와 평점을 실제 리뷰에서 다시 계산해 채웁니다.
update jobs
set review_count = sub.cnt,
    rating       = sub.avg_rating
from (
  select job_id, count(*) as cnt, round(avg(rating)::numeric, 1) as avg_rating
  from job_reviews
  group by job_id
) as sub
where jobs.id = sub.job_id;

